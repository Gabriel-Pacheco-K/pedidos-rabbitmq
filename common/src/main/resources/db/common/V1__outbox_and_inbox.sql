-- Tabelas de infraestrutura, iguais em todos os serviços.

CREATE TABLE outbox_events (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id   UUID         NOT NULL UNIQUE,
    routing_key  VARCHAR(60)  NOT NULL,
    payload      TEXT         NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    published_at TIMESTAMP WITH TIME ZONE,
    attempts     INT          NOT NULL DEFAULT 0,
    last_error   VARCHAR(500)
);

-- Índice parcial: o relay só procura eventos pendentes, então indexa só eles.
CREATE INDEX idx_outbox_pending ON outbox_events (id) WHERE published_at IS NULL;

CREATE TABLE processed_messages (
    message_id   UUID        PRIMARY KEY,
    routing_key  VARCHAR(60) NOT NULL,
    processed_at TIMESTAMP WITH TIME ZONE NOT NULL
);
