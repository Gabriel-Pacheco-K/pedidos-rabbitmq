CREATE TABLE products (
    sku    VARCHAR(30)    PRIMARY KEY,
    name   VARCHAR(100)   NOT NULL,
    price  NUMERIC(12, 2) NOT NULL CHECK (price > 0),
    active BOOLEAN        NOT NULL DEFAULT TRUE
);

CREATE TABLE orders (
    id              UUID           PRIMARY KEY,
    customer_id     VARCHAR(100)   NOT NULL,
    status          VARCHAR(12)    NOT NULL CHECK (status IN ('PENDING', 'CONFIRMED', 'CANCELLED', 'REJECTED')),
    status_reason   VARCHAR(255),
    total           NUMERIC(14, 2) NOT NULL CHECK (total > 0),
    idempotency_key UUID           NOT NULL,
    request_hash    VARCHAR(64)    NOT NULL,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    version         BIGINT         NOT NULL,
    -- A mesma chave de idempotência só cria um pedido por cliente, mesmo com requisições simultâneas.
    CONSTRAINT uq_orders_idempotency UNIQUE (customer_id, idempotency_key)
);

CREATE TABLE order_items (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id   UUID           NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    sku        VARCHAR(30)    NOT NULL REFERENCES products (sku),
    quantity   INT            NOT NULL CHECK (quantity BETWEEN 1 AND 100),
    unit_price NUMERIC(12, 2) NOT NULL CHECK (unit_price > 0),
    CONSTRAINT uq_order_item UNIQUE (order_id, sku)
);

