CREATE TABLE stock (
    sku       VARCHAR(30) PRIMARY KEY,
    available INT         NOT NULL CHECK (available >= 0),
    reserved  INT         NOT NULL CHECK (reserved >= 0)
);

CREATE TABLE reservations (
    order_id   UUID           PRIMARY KEY,
    status     VARCHAR(10)    NOT NULL CHECK (status IN ('RESERVED', 'COMMITTED', 'RELEASED', 'REJECTED')),
    amount     NUMERIC(14, 2) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE reservation_lines (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id UUID        NOT NULL REFERENCES reservations (order_id) ON DELETE CASCADE,
    sku      VARCHAR(30) NOT NULL,
    quantity INT         NOT NULL CHECK (quantity > 0),
    CONSTRAINT uq_reservation_line UNIQUE (order_id, sku)
);

